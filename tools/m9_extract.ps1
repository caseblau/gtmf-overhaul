<#
.SYNOPSIS
  M9: re-express night_postman's Achtung Panzer Ostfront Mius Configs as a delta on the 6.00 build 3598 tables.

.DESCRIPTION
  Input : <GameRoot>\users\modwork\_orig\3598\{tabs,tabs_oprum}\*.config.loc_def.bin   (pristine vanilla)
          build\tp\apcfg_unp\*                                                          (his archive, unpacked)
  Output: src\m9_ap_port\mfo_tabs_ap\<entry>.config.loc_def.delta   the kept part of  gt3.ps1 diff vanilla -> AP  (what the
                                                                     module ships; build.ps1 applies it to vanilla at build time)
          src\m9_ap_port\mfo_tabs_ap\trans_marks0_dift*.texture.loc_def.bin, !flatlist
          build\m9_merged\<entry>.config.loc_def.bin   vanilla + delta, for the reference checks below only
          build\m9_raw\<entry>.delta                   the unfiltered diff, for reference
  Rules (docs/third_party.md 3.1, DESIGN.md M9): keep what binds his models, drop what reverts 6.00 content.
    outfit_hum*, ger_hum_base*, rus_hum_base*  keep node+ (new soldier/outfit structs) and row+ / row~ (re-bound meshes,
                                               skins, ammo and outfit patterns); drop node-, row-, types~ (his 2021
                                               snapshot lacks post-2021 nations and soldiers; struct type strings
                                               are regenerated by the writer)
    hum_params                                 keep node+ / row+ / row~ under links_* only (model attachment points);
                                               drop speech_* and every removal
    div_units_ger, div_units_ussr              keep row+ / row~ of node `units` only (unit -> soldier-type bindings);
                                               drop his squads, randoms, trophy, supports and all removals
    common_res_mod, qbattle                    not ported at all
  Then it checks that every i_human unit row points at a soldier type that exists in the merged tables (all seasons),
  that every ammo_pat exists in vanilla ammo_hum and every outfit_pat in the merged outfit tables.
#>
param([string]$GameRoot = $env:GTMF_ROOT)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$gt3 = Join-Path $PSScriptRoot 'gt3.ps1'
if (-not $GameRoot) { throw 'set GTMF_ROOT or pass -GameRoot' }
$orig = Join-Path $GameRoot 'users\modwork\_orig\3598'
$ap = Join-Path $repo 'build\tp\apcfg_unp'
$raw = Join-Path $repo 'build\m9_raw'
$outMod = Join-Path $repo 'src\m9_ap_port'
$arc = Join-Path $outMod 'mfo_tabs_ap'
$mergedDir = Join-Path $repo 'build\m9_merged'
foreach ($d in $raw, $mergedDir, $arc) { New-Item -ItemType Directory -Force $d | Out-Null }

$entries = 'outfit_hum', 'outfit_hum_autumn', 'outfit_hum_winter',
           'ger_hum_base', 'ger_hum_base_autumn', 'ger_hum_base_winter',
           'rus_hum_base', 'rus_hum_base_autumn', 'rus_hum_base_winter',
           'hum_params', 'div_units_ger', 'div_units_ussr'
function Vanilla([string]$e) {
    foreach ($a in 'tabs', 'tabs_oprum') { $p = Join-Path $orig "$a\$e.config.loc_def.bin"; if (Test-Path $p) { return $p } }
    throw "no vanilla table for $e"
}
function Keep([string]$e, [string]$op, [string]$path) {
    if ($e -like 'div_units_*') { return ($path -eq 'units' -and ($op -eq 'row+' -or $op -eq 'row~')) }
    if ($e -eq 'hum_params') { return ($path -like 'links_*' -and ($op -eq 'node+' -or $op -eq 'row+' -or $op -eq 'row~')) }
    return ($op -eq 'node+' -or $op -eq 'row+' -or $op -eq 'row~')
}

function NodeNames([string]$bin) { (& $gt3 nodes $bin 0 | Select-Object -Skip 1) | ForEach-Object { if ($_ -match '^\s+\[\s*\d+\]\s+(\S+)\s+type=') { $Matches[1] } } }
function Fields([string]$line) { ($line -replace '\\\|', "`0") -split '\|' | ForEach-Object { $_.Replace("`0", '|').Replace('\\', '\') } }
function Structs([string]$bin) {
    # node name -> hashtable of struct fields (text values), from the azcf dump
    $out = @{}; $cur = $null
    foreach ($l in (& $gt3 azcf $bin)) {
        if ($l -match '^\[\d+\]\s+(\S*)\s+type=(\d)') { $cur = @{}; if ($Matches[2] -eq '1' -and $Matches[1]) { $out[$Matches[1]] = $cur } }
        elseif ($cur -ne $null -and $l -match '^\s+(\w+)\s+=\s+(.*)$') { $cur[$Matches[1]] = $Matches[2].Trim() }
    }
    $out
}
# Every mesh and texture entry of every archive on this install (DataBase add-on included): tools\catalog.ps1 output.
# A soldier's dif_skin X is the texture entry reg_X, its norsp_skin Y is bump_Y, its mesh is a mesh entry (checked on
# vanilla: 223/223 resolve). His tables carry 17 skin names that exist nowhere (typos such as spg_lieuten_sdift, or
# bare _dift); a unit bound to such a soldier type crashed the renderer in quick battle (0.2.6, 2026-10-15).
$catalog = @{}
foreach ($l in Get-Content (Join-Path $repo 'docs\archive_catalog.txt')) { if ($l -match '^\s{4}(\S+)\s+(\S+)\s+(\S+)\s') { $catalog[$Matches[1] + '|' + $Matches[2]] = 1 } }
if ($catalog.Count -lt 1000) { throw 'docs\archive_catalog.txt is missing or empty; run tools\catalog.ps1 first' }
function Entry([string]$name) { if ($name.Length -gt 31) { $name.Substring(0, 31) } else { $name } }   # entry names are char[0x20]
function SkinOk([string]$field, [string]$value) {
    if ($value -eq '') { return $true }
    switch ($field) { 'mesh' { $catalog.ContainsKey((Entry $value) + '|mesh') } 'dif_skin' { $catalog.ContainsKey((Entry "reg_$value") + '|texture') } 'norsp_skin' { $catalog.ContainsKey((Entry "bump_$value") + '|texture') } default { $true } }
}
# Our corrections of plain typos in his tables: the intended texture exists in his DataBase. Applied as extra row~ ops
# (struct rows are keyed by field name). Everything else that does not resolve stays broken and unbound.
$fixups = @{
    'ger_hum_base' = @('row~|ger_spg_kompfuhrer|dif_skin|c0=s:spg_lieuten_s_dift', 'row~|ger_spg_zugfuhrer|dif_skin|c0=s:spg_lieuten_s_dift')
    'rus_hum_base' = @('row~|rus_rifle_major|dif_skin|c0=s:rkka_major_s_dift', 'row~|rus_rifle_major|norsp_skin|c0=s:rkka_major_s_norsp',
                       'row~|rus_motrifle_major|dif_skin|c0=s:rkka_major_s_dift', 'row~|rus_motrifle_major|norsp_skin|c0=s:rkka_major_s_norsp')
}
function BrokenTypes([string]$bin) {
    # soldier structs whose effective mesh / dif_skin / norsp_skin (own field, else inherited through `redirect`) is missing
    $s = Structs $bin; $bad = @{}
    foreach ($name in $s.Keys) {
        foreach ($f in 'mesh', 'dif_skin', 'norsp_skin') {
            $n = $name; $v = ''; $hops = 0
            while ($n -and $s.ContainsKey($n) -and $hops -lt 12) { if ($s[$n].ContainsKey($f) -and $s[$n][$f] -ne '') { $v = $s[$n][$f]; break }; $n = $(if ($s[$n].ContainsKey('redirect')) { $s[$n]['redirect'] } else { '' }); $hops++ }
            if (-not (SkinOk $f $v)) { $bad[$name] = "$f=$v" }
        }
    }
    $bad
}

$report = New-Object Collections.Generic.List[string]
$report.Add("# M9 extraction report $(Get-Date -Format s)")
$merged = @{}
$broken = @{}
$unresolved = New-Object Collections.Generic.List[string]
$badrefs = New-Object Collections.Generic.List[string]
foreach ($e in $entries) {
    $van = Vanilla $e
    $src = Join-Path $ap "$e.config.loc_def.bin"
    $rawDelta = Join-Path $raw "$e.delta"
    & $gt3 diff $van $src $rawDelta | Out-Null
    $kept = New-Object Collections.Generic.List[string]
    $counts = @{}
    $vanUnits = @{}
    $anchorRemap = @{}
    if ($e -like 'div_units_*') {
        # soldier types the merged *_hum_base tables (written above) actually define, minus the ones whose skins are
        # missing in any season; a unit must point at one of the rest
        foreach ($t in 'ger_hum_base', 'rus_hum_base') {
            if ($merged.ContainsKey($t)) { continue }
            $merged[$t] = @(NodeNames (Join-Path $mergedDir "$t.config.loc_def.bin"))
            $broken[$t] = @{}
            foreach ($season in '', '_autumn', '_winter') { $b = BrokenTypes (Join-Path $mergedDir "$t$season.config.loc_def.bin"); foreach ($k in $b.Keys) { $broken[$t][$k] = "$t$season $($b[$k])" } }
        }
        $csv = & $gt3 csv $van units
        foreach ($row in ($csv | Select-Object -Skip 1 | ConvertFrom-Csv -Header (0..16 | ForEach-Object { "c$_" }))) { $vanUnits[$row.c0] = $row.c3 }
    }
    foreach ($line in [IO.File]::ReadAllLines($rawDelta, (New-Object Text.UTF8Encoding $false))) {
        if ($line -eq '' -or $line.StartsWith('#')) { continue }
        $op = $line.Substring(0, $line.IndexOf('|'))
        $rest = $line.Substring($op.Length + 1)
        # path = up to the next unescaped '|'
        $m = [regex]::Match($rest, '^((?:\\.|[^|\\])*)')
        $path = $m.Groups[1].Value.Replace('\|', '|').Replace('\\', '\')
        $k = if (Keep $e $op $path) { 'kept' } else { 'dropped' }
        # his converter left comment text as struct rows of kind 7 with no field name: junk, never port it
        if ($k -eq 'kept' -and $op -eq 'row+' -and $line -match '\|k\d+:[0-9a-f]{8};') { $k = 'junk' }
        # a unit binding is only taken when the soldier type it names exists in the merged table it points at
        if ($k -eq 'kept' -and $e -like 'div_units_*') {
            $f = Fields $line; $file = ''; $type = ''
            if ($op -eq 'row+') { $cells = $f[4..($f.Count - 1)]; if ($cells[2] -eq 's:i_human') { $file = $cells[3] -replace '^s:', ''; $type = $cells[4] -replace '^s:', '' } }
            else { $c4 = $f | Where-Object { $_ -like 'c4=*' } | Select-Object -First 1; if ($c4 -and $vanUnits.ContainsKey($f[2])) { $file = $vanUnits[$f[2]]; $type = $c4 -replace '^c4=s:', '' } }
            if ($file) {
                $t = $file -replace '^tabs\\', '' -replace '\.cfgpack$', ''
                if ($merged.ContainsKey($t) -and ($merged[$t] -notcontains $type)) { $k = 'unresolved'; $unresolved.Add("$e $op $($f[2]) -> $t/$type (no such soldier type)") }
                elseif ($broken.ContainsKey($t) -and $broken[$t].ContainsKey($type)) { $k = 'unresolved'; $unresolved.Add("$e $op $($f[2]) -> $t/$type (skin missing: $($broken[$t][$type]))") }
            }
        }
        # a re-bound skin or mesh on a vanilla soldier must exist in some archive
        if ($k -eq 'kept' -and $op -eq 'row~' -and $line -match '\|c0=s:(.*)$' -and $path -notlike '*/*') {
            $f = Fields $line; $field = $f[2]; $value = $f[3] -replace '^c0=s:', ''
            if (-not (SkinOk $field $value)) { $k = 'badref'; $badrefs.Add("$e $path.$field=$value") }
        }
        # a row+ names the row it goes behind; when that row was dropped above, anchor on what the dropped row anchored on
        if ($op -eq 'row+' -and $line -match '^(row\+)\|((?:\\.|[^|\\])*)\|((?:\\.|[^|\\])*)\|((?:\\.|[^|\\])*)\|(.*)$') {
            $rawPath = $Matches[2]; $after = $Matches[3]; $rawKey = $Matches[4]; $rest = $Matches[5]
            if ($anchorRemap.ContainsKey("$rawPath|$after")) { $after = $anchorRemap["$rawPath|$after"]; $line = "row+|$rawPath|$after|$rawKey|$rest" }
            if ($k -ne 'kept') { $anchorRemap["$rawPath|$rawKey"] = $after }
        }
        $key = "$k $op"; if ($counts.ContainsKey($key)) { $counts[$key]++ } else { $counts[$key] = 1 }
        if ($k -eq 'kept') { $kept.Add($line) }
    }
    if ($fixups.ContainsKey($e)) { foreach ($fx in $fixups[$e]) { $kept.Add($fx) }; $counts['fixup row~'] = $fixups[$e].Count }
    $summary = (($counts.Keys | Sort-Object | ForEach-Object { "$_=$($counts[$_])" }) -join ' ')
    $hdr = @("# M9 delta for $e : night_postman's bindings (Achtung Panzer Ostfront Mius Configs v1118) on 6.00 build 3598",
             "# generated by tools\m9_extract.ps1 $(Get-Date -Format s) from  gt3.ps1 diff vanilla -> AP ; $summary")
    $deltaPath = Join-Path $arc "$e.config.loc_def.delta"
    [IO.File]::WriteAllLines($deltaPath, [string[]]($hdr + $kept), (New-Object Text.UTF8Encoding $false))
    $outBin = Join-Path $mergedDir "$e.config.loc_def.bin"
    $applied = & $gt3 apply $van $deltaPath $outBin
    $line = '{0,-22} {1}  ->  {2}' -f $e, $summary, ($applied | Select-Object -First 1)
    $line; $report.Add($line)
}
foreach ($t in Get-ChildItem $ap -Filter 'trans_marks0_dift*.texture.loc_def.bin') { Copy-Item $t.FullName $arc -Force; $report.Add("copied $($t.Name)") }
# !flatlist lists every entry the module contributes: the 12 delta tables and the 2 whole textures
$list = @('i_unflat:unflat()', '{')
foreach ($f in Get-ChildItem $arc -File | Where-Object { $_.Name -match '\.(bin|delta)$' } | Sort-Object Name) {
    if ($f.Name -match '^(.+?)\.(\w+)\.(\w+)\.(bin|delta)$') { $list += ("`t{0,-30}, {1,-16}, {2} ;" -f $Matches[1], $Matches[2], $Matches[3]) }
}
$list += '}'
[IO.File]::WriteAllLines((Join-Path $arc '!flatlist'), $list, [Text.Encoding]::ASCII)

# ---- reference checks on the merged tables ----
$report.Add("unit bindings left at vanilla because the soldier type does not exist or its skins are missing in his files too: $($unresolved.Count)")
$unresolved | ForEach-Object { $report.Add("  $_") }
$report.Add("skin/mesh re-bindings of vanilla soldiers dropped because the texture exists nowhere: $($badrefs.Count)")
$badrefs | ForEach-Object { $report.Add("  $_") }
foreach ($t in $broken.Keys) { $report.Add("$t soldier types with missing skins (not bindable): $($broken[$t].Count): " + (($broken[$t].Keys | Sort-Object | ForEach-Object { "$_ [$($broken[$t][$_])]" }) -join '; ')) }
function StructFields([string]$bin, [string]$field) {
    # (node, value) pairs for a struct field, from the azcf dump
    $node = ''
    foreach ($l in (& $gt3 azcf $bin)) {
        if ($l -match '^\[\d+\]\s+(\S*)\s+type=') { $node = $Matches[1] }
        elseif ($l -match "^\s+$field\s+=\s+(.*)$") { [pscustomobject]@{ node = $node; value = $Matches[1].Trim() } }
    }
}
$problems = New-Object Collections.Generic.List[string]
foreach ($e in $entries) { $merged[$e] = @(NodeNames (Join-Path $mergedDir "$e.config.loc_def.bin")) }
$ammoNodes = @(NodeNames (Join-Path $orig 'tabs\ammo_hum.config.loc_def.bin'))
foreach ($side in 'ger', 'ussr') {
    $csv = & $gt3 csv (Join-Path $mergedDir "div_units_$side.config.loc_def.bin") units
    $rows = $csv | Select-Object -Skip 1 | ConvertFrom-Csv -Header (0..16 | ForEach-Object { "c$_" })
    $n = 0
    foreach ($row in $rows) {
        if ($row.c2 -ne 'i_human') { continue }
        $file = $row.c3 -replace '^tabs\\', '' -replace '\.cfgpack$', ''
        if (-not $merged.ContainsKey($file)) { continue }
        $n++
        foreach ($season in '', '_autumn', '_winter') {
            $t = "$file$season"
            if ($merged.ContainsKey($t) -and ($merged[$t] -notcontains $row.c4)) { $problems.Add("div_units_$side units $($row.c0): soldier type '$($row.c4)' missing in $t") }
        }
    }
    $report.Add("div_units_$side : $n i_human rows checked against the merged *_hum_base tables")
}
foreach ($e in 'ger_hum_base', 'ger_hum_base_autumn', 'ger_hum_base_winter', 'rus_hum_base', 'rus_hum_base_autumn', 'rus_hum_base_winter') {
    $bin = Join-Path $mergedDir "$e.config.loc_def.bin"
    $outfitTable = if ($e -like '*_autumn') { 'outfit_hum_autumn' } elseif ($e -like '*_winter') { 'outfit_hum_winter' } else { 'outfit_hum' }
    $na = 0; $no = 0
    foreach ($f in StructFields $bin 'ammo_pat') { $na++; if ($f.value -and ($ammoNodes -notcontains $f.value)) { $problems.Add("$e/$($f.node): ammo_pat '$($f.value)' not in vanilla ammo_hum") } }
    foreach ($f in StructFields $bin 'outfit_pat') { $no++; if ($f.value -and ($merged[$outfitTable] -notcontains $f.value)) { $problems.Add("$e/$($f.node): outfit_pat '$($f.value)' not in merged $outfitTable") } }
    foreach ($f in StructFields $bin 'redirect') { if ($f.value -and ($merged[$e] -notcontains $f.value)) { $problems.Add("$e/$($f.node): redirect '$($f.value)' not in merged $e") } }
    $report.Add("$e : $na ammo_pat and $no outfit_pat references checked")
}
$report.Add("reference problems: $($problems.Count)")
$problems | ForEach-Object { $report.Add("  $_") }
[IO.File]::WriteAllLines((Join-Path $outMod 'extract_report.txt'), $report, (New-Object Text.UTF8Encoding $false))
$report | Select-Object -Skip ($entries.Count + 1)
"wrote $arc\*.delta (+ textures, !flatlist), $mergedDir\*.bin (check copies) and $outMod\extract_report.txt"
