<#
.SYNOPSIS
  Regenerates src\m8_vfx\mfo_vfx\parts.config.loc_def.61_autumn.delta: parts_desc_aut override rows (matched by name, like the
  vanilla winter rows) copied from the CURRENT merged summer rows with the wet-ground autumn palette applied.
  Run after every change to the summer dust / earth / column rows, then build again, or autumn maps keep stale values.
.EXAMPLE
  tools\gen_autumn.ps1      (needs a prior build.ps1 run for build\merge\mfo_vfx\parts.config.loc_def.bin)
#>
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$gt3 = Join-Path $PSScriptRoot 'gt3.ps1'
$merged = Join-Path $repo 'build\merge\mfo_vfx\parts.config.loc_def.bin'
function A([string]$h) { $u = [Convert]::ToUInt32($h, 16); if ($u -ge 2147483648) { [string]([int64]$u - 4294967296) } else { [string]$u } }
function C([string]$list) { (($list -split ';') | ForEach-Object { A $_ }) -join ';' }
$csv = @(& powershell -NoProfile -ExecutionPolicy Bypass -File $gt3 csv $merged parts_desc)
$kinds = ($csv[0] -split ',') | ForEach-Object { ($_ -split ':')[1] }
function Cells([string]$line) { $o = New-Object Collections.Generic.List[string]; foreach ($m in [regex]::Matches($line, '("([^"]*)"|[^,]*)(,|$)')) { if ($m.Groups[2].Success) { $o.Add($m.Groups[2].Value) } else { $o.Add($m.Groups[1].Value) } }; $o }
function Enc([string]$k, [string]$v) { switch ($k) { 's' { 's:' + $v } 'u' { if ($v -match '^\d+$') { "u:$v" } else { "u:'$v'" } } 'v' { "v:$v" } 'a' { "a:$v" } 'f' { "f:$v" } 'b' { "b:$v" } } }
# autumn = wet ground: dust darker, browner, thinner; earth, clods and the burst column dark wet brown. Only colours are overridden;
# sizes, counts, lifetimes and physics follow the summer rows.
$aut = @{
    'dust_expl_rnd_sm'  = @{ 11 = (C 'A0887C64;78786C56'); 12 = (A '00887C64') }
    'dust_expl_rnd'     = @{ 11 = (C 'A0887C64;78786C56'); 12 = (A '00887C64') }
    'dust_expl_rnd_big' = @{ 11 = (C 'A0887C64;78786C56'); 12 = (A '00887C64') }
    'dust_wh'           = @{ 11 = (C '80887C64;30887C64'); 12 = (A '00887C64') }
    'dust_shot'         = @{ 11 = (A 'A0887C64'); 12 = (A '00887C64') }
    'dust_shot_rnd'     = @{ 11 = (C '90887C64;60887C64'); 12 = (A '00887C64') }
    'dirt_expl'         = @{ 11 = (A 'FF3A3226'); 12 = (A '003A3226') }
    'dirt_expl_big'     = @{ 11 = (A 'FF40382A'); 12 = (A '0040382A') }
    'dirt_bomb'         = @{ 11 = (A 'FF40382A'); 12 = (A '0040382A') }
    'ext_dirt'          = @{ 11 = (A 'FF3E3628'); 12 = (A 'FF3E3628') }
    'core_expl'         = @{ 11 = (A 'FF403A30'); 12 = (A '00564E44') }
    'core_expl_bomb'    = @{ 11 = (A 'FF403A30'); 12 = (A '00564E44') }
}
$lines = New-Object Collections.Generic.List[string]
$lines.Add('# MF Overhaul: autumn override rows (parts_desc_aut, matched by name like the vanilla winter rows). GENERATED by tools\gen_autumn.ps1')
$lines.Add("#   on $(Get-Date -Format 'yyyy-MM-dd HH:mm') from the merged summer rows; only the colours differ (wet-ground palette: dust 0x887C64,")
$lines.Add('#   earth / clods / column 0x3A3226 / 0x40382A / 0x403A30). Re-run the script after changing the summer rows.')
$lines.Add("# $($aut.Count) operations")
foreach ($line in ($csv | Select-Object -Skip 1)) {
    $c = Cells $line; $name = $c[0]; if (-not $aut.ContainsKey($name)) { continue }
    $ov = $aut[$name]
    $enc = for ($i = 0; $i -lt $kinds.Count; $i++) { $v = if ($ov.ContainsKey($i)) { $ov[$i] } else { $c[$i] }; Enc $kinds[$i] $v }
    $lines.Add('row+|parts_desc_aut|@end|' + $name + '|' + ($enc -join '|'))
}
$out = Join-Path $repo 'src\m8_vfx\mfo_vfx\parts.config.loc_def.61_autumn.delta'
[IO.File]::WriteAllLines($out, $lines, (New-Object Text.UTF8Encoding $false))
"wrote $($lines.Count - 4) autumn rows to $out"
